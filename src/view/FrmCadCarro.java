    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        if (!lista.isEmpty()) {
            int id = Integer.parseInt(txtId.getText());
            int pos = -1;
            for (int i = 0; i < lista.size(); i++) {
                if (id == lista.get(i).getId()) {
                    pos = i;
                    break; // Adicionei um break aqui para ele parar de procurar assim que achar!
                }
            }
            
            if (pos != -1) {
                int remover = JOptionPane.showConfirmDialog(this, "Você tem certeza que deseja apagar:\n"
                        + lista.get(pos).toString(), "Excluir", JOptionPane.YES_NO_OPTION);
                
                if (remover == JOptionPane.YES_OPTION) {
                    // Chama o DAO para excluir do Banco
                    dao.exlcuirCarro(lista.get(pos).getId()); // Obs: "excluir" está escrito "exlcuir", cuidado rsrs
                    
                    // Atualiza a lista
                    lista.clear();
                    lista = dao.getCarros();
                    
                    // AGORA SIM: Verifica se a lista ficou vazia ANTES de tentar mostrar na tela
                    if(lista.isEmpty()) {
                        limparCampos();
                        desabilitarTodosBotoes();
                    } else {
                        btnAnterior.setEnabled(false);
                        if(lista.size() - 1 == 0) {
                           btnProximo.setEnabled(false);
                        }
                        
                        indice = 0; // Vai pro primeiro carro
                        mostrarDadosTela(); // Mostra na tela em segurança!
                    }
                }
            } else {
                JOptionPane.showMessageDialog(this, "O modelo pesquisado não se encontra na lista");
            }

        } else {
            JOptionPane.showMessageDialog(this, "Não existem modelos cadastrados");
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

