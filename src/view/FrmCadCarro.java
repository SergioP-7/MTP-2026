    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed

  try {
            Carro meucarro = new Carro();

            meucarro.setModelo(txtModelo.getText());
            meucarro.setMarca(txtMarca.getText());
            
            // Se o usuário digitar letras aqui, o Java pula direto pro 'catch' lá embaixo!
            meucarro.setAno(Integer.parseInt(txtAno.getText()));

            dao.salvarCarro(meucarro);
            
            JOptionPane.showMessageDialog(this, "Carro salvo com sucesso!!!");
            
            lista.clear();
            lista = dao.getCarros();
            
            if(lista.size() - 1 == 0) {
                btnPrimeiro.setEnabled(true);
                btnUltimo.setEnabled(true);
            } else {
                btnAnterior.setEnabled(true);
            }
            
            indice = lista.size() - 1;
            mostrarDadosTela();
            
        } catch (NumberFormatException e) {
            // Se der erro na conversão do número, avisa o usuário educadamente:
            JOptionPane.showMessageDialog(this, "Por favor, digite apenas números no campo Ano!");
        }

    }//GEN-LAST:event_btnSalvarActionPerformed

